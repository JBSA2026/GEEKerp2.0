-- Selecting a new primary contact demotes the client's previous primary contact.
CREATE OR REPLACE FUNCTION public.contact_list_single_primary() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.is_primary_contact THEN
        UPDATE public.contact_list
           SET is_primary_contact = false
         WHERE client_id = NEW.client_id
           AND is_primary_contact
           AND contact_id IS DISTINCT FROM NEW.contact_id;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_contact_list_single_primary
    BEFORE INSERT OR UPDATE OF is_primary_contact, client_id ON public.contact_list
    FOR EACH ROW EXECUTE FUNCTION public.contact_list_single_primary();

