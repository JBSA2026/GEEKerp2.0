    ADD COLUMN ewt_material numeric GENERATED ALWAYS AS
        (CASE WHEN coalesce(currency_code, 'PHP') = 'PHP'
              THEN round(coalesce(vat_exclusive_amount, 0) * 0.01, 2) ELSE 0 END) STORED,
